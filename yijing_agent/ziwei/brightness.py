def _build():
    table = {}
    for branch, cols in _RAW.items():
        for level, cell in zip(LEVELS, cols):
            for ch in cell:
                key = (ABBR[ch], branch)
                assert key not in table, f"庙陷表重复：{key}"
                table[key] = level
    return table


_TABLE = _build()


def of(star: str, branch: str):
    """星在某支宫的亮度等级；底本未列者返回 None。"""
    return _TABLE.get((star, branch))
